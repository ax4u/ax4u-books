import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] });
const base = process.env.TEST_BASE_URL || 'http://localhost:3100';
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base);
  await page.getByRole('link', { name: '오픈 그림책 전시회', exact: true }).click();
  await page.waitForURL(base + '/exhibition');
  assert.equal(new URL(page.url()).pathname, '/exhibition');
  await page.getByRole('link', { name: /행성 친구들의 우당당탕 여행/ }).click();
  const reader = page.getByRole('region', { name: '그림책 읽기' });
  await reader.waitFor();
  await page.waitForFunction(() => document.querySelector('[data-page-image]')?.naturalWidth > 0);
  assert.equal(await page.getByRole('button', { name: '이전 페이지' }).isDisabled(), true);
  assert.equal(await page.locator('[data-page-image]').getAttribute('src'), '/exhibition/planet-friends/cover.png');
  await page.getByRole('button', { name: '다음 페이지' }).click();
  assert.match(await page.getByRole('status').innerText(), /본문 1쪽/);
  await reader.focus();
  await page.keyboard.press('End');
  assert.match(await page.getByRole('status').innerText(), /본문 28쪽/);
  assert.equal(await page.getByRole('button', { name: '다음 페이지' }).isDisabled(), true);
  await page.keyboard.press('Home');
  await page.keyboard.press('ArrowRight');
  assert.match(await page.getByRole('status').innerText(), /본문 1쪽/);
  await page.getByLabel('페이지 선택').selectOption('14');
  assert.match(await page.getByRole('status').innerText(), /본문 14쪽/);
  const notFound = await page.goto(base + '/exhibition/private-book');
  assert.equal(notFound.status(), 404);
  const mobile = await context.newPage({});
  await mobile.setViewportSize({ width: 375, height: 812 });
  await mobile.emulateMedia({ reducedMotion: 'reduce' });
  const images = new Set();
  mobile.on('request', r => { if (r.url().includes('/exhibition/planet-friends/') && r.url().endsWith('.png')) images.add(r.url()); });
  await mobile.goto(base + '/exhibition/planet-friends');
  await mobile.waitForFunction(() => document.querySelector('[data-page-image]')?.naturalWidth > 0);
  assert.ok(images.size <= 2, `Initial page fetched ${images.size} full PNGs`);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const stage = mobile.locator('[data-page-stage]');
  await stage.evaluate(el => {
    const start = new Touch({ identifier: 1, target: el, clientX: 300, clientY: 300 });
    const end = new Touch({ identifier: 1, target: el, clientX: 100, clientY: 310 });
    el.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }));
    el.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }));
  });
  assert.match(await mobile.getByRole('status').innerText(), /본문 1쪽/);
  assert.equal(await mobile.locator('[data-page-image]').evaluate(el => getComputedStyle(el).animationName), 'none');
  await mobile.waitForFunction(() => document.querySelector('[data-page-image]')?.naturalWidth > 0);
  await mobile.screenshot({ path: '/tmp/ax4u-exhibition-mobile.png', fullPage: true });
  await page.goto(base + '/exhibition/planet-friends');
  await page.waitForFunction(() => document.querySelector('[data-page-image]')?.naturalWidth > 0);
  await page.screenshot({ path: '/tmp/ax4u-exhibition-desktop.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: anonymous menu/gallery/reader, cover + navigation + boundaries, keyboard, selection, unknown slug 404, mobile swipe, reduced motion, no overflow, lazy requests, no browser errors');
} finally { await browser.close(); }
